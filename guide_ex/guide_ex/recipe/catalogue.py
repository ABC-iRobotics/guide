"""The catalogue of guide_ex's nodes: every @node leaf and every library recipe, what it takes and gives,
and which recipes use it. `python -m guide_ex.recipe catalogue` writes CATALOGUE.md and
catalogue.json (package root); test_recipe_catalogue.py fails while they differ from a fresh render."""

import ast
import inspect
import json
import re
import textwrap
from pathlib import Path

from guide_ex.core.states import Layer
from guide_ex.recipe.registry import LEAF_PACKAGES, LIBRARY, PACKAGE, RecipeTemplate, load_defaults

INTERPOLATION = re.compile(r"\$\{([^}]+)\}")


def _refs(spec) -> list[str]:
    """Every name `spec` refs, at any depth (children, fallbacks, branches, overrides)."""
    if isinstance(spec, dict):
        own = [spec["ref"]] if isinstance(spec.get("ref"), str) else []
        return own + [r for v in spec.values() for r in _refs(v)]
    if isinstance(spec, list):
        return [r for v in spec for r in _refs(v)]
    return []


def _doc(text: str | None) -> str:
    """The first paragraph of a docstring or comment block, as one line."""
    return " ".join(textwrap.dedent(text or "").strip().split("\n\n")[0].split())


def _outputs(cls) -> list[str]:
    """The keys run() puts in an ExecutionResult's outputs={...}, read from its source."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(cls.run)))
    return sorted({key.value for call in ast.walk(tree) if isinstance(call, ast.Call)
                   for kw in call.keywords if kw.arg == "outputs" and isinstance(kw.value, ast.Dict)
                   for key in kw.value.keys if isinstance(key, ast.Constant)})


def _leaf(name: str, cls) -> dict:
    params = [p for n, p in inspect.signature(cls.run).parameters.items() if n != "self"]
    return {
        "name": name, "kind": "leaf", "level": cls.level.name,
        "inputs": [f"**{p.name}" if p.kind == p.VAR_KEYWORD else p.name if p.default is p.empty
                   else f"{p.name}={p.default!r}" for p in params],
        "outputs": _outputs(cls),
        "doc": _doc(cls.__doc__) or _doc(cls.run.__doc__),
        "source": Path(inspect.getfile(cls)).resolve().relative_to(PACKAGE).as_posix(),
    }


def _recipe(template: RecipeTemplate, nodes: dict) -> dict:
    spec = template.spec
    ref = nodes.get(spec.get("ref"), {})
    comments = []
    for line in template.path.read_text().splitlines():  # the file's leading comment block
        if not line.startswith("#"):
            break
        comments.append(line[1:])
    return {
        "name": template.name, "kind": "recipe", "level": spec.get("level") or ref.get("level"),
        "inputs": sorted(set((spec.get("dynamic_map") or {}).values()))
        + sorted({f"${{{v}}}" for v in INTERPOLATION.findall(json.dumps(spec))}),
        "outputs": sorted((spec.get("output_map") or {}).values()) or ref.get("outputs", []),
        "doc": _doc("\n".join(comments)),
        "source": template.path.relative_to(PACKAGE).as_posix(),
    }


def entries() -> list[dict]:
    """One entry per leaf and library recipe, highest level first, then by name."""
    registry = load_defaults()
    leaves, templates = {}, []
    for name in registry.names():
        target = registry.resolve(name)
        if isinstance(target, RecipeTemplate):
            if any(target.path.is_relative_to(folder) for folder in LIBRARY):
                templates.append(target)
        else:
            file = Path(inspect.getfile(target)).resolve()
            if file.is_relative_to(PACKAGE) and file.relative_to(PACKAGE).parts[0] in LEAF_PACKAGES:  # outside leaves skipped
                leaves[name] = _leaf(name, target)
    nodes = dict(leaves)
    for template in sorted(templates, key=lambda t: t.spec.get("ref") is None):  # leaf presets first
        nodes[template.name] = _recipe(template, nodes)
    for entry in nodes.values():
        entry["used_by"] = sorted(t.name for t in templates if entry["name"] in _refs(t.spec))
    return sorted(nodes.values(), key=lambda e: (-Layer[e["level"]].value, e["name"]))


def render() -> tuple[str, str]:
    """(CATALOGUE.md, catalogue.json) as text."""
    nodes = entries()
    rows = [
        f"| {e['name']} | {e['kind']} | {e['level']} | {', '.join(e['inputs'])} | {', '.join(e['outputs'])} "
        f"| {e['doc']} | {e['source']} | {', '.join(e['used_by'])} |"
        for e in nodes
    ]
    md = "\n".join([
        "# GUIDE-EX node catalogue",
        "",
        "Generated by `python -m guide_ex.recipe catalogue` (run from `guide_ex/`); do not edit.",
        "A leaf is a Python class registered with `@node`; it takes `alias`, `dynamic_map`, `static_args`",
        "and `output_map`, and its inputs are its `run()` arguments. A recipe is a YAML file under",
        "its level's folder (`steps/`, `sequences/`, `subtasks/`, `tasks/`, `utility/`), named by its file stem; its inputs are the context keys its `dynamic_map`",
        "reads and the `${...}` values its file interpolates (`load(values=...)`).",
        "",
        "| Name | Kind | Level | Inputs | Outputs | Description | Source | Used by |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ])
    return md, json.dumps({"nodes": nodes}, indent=2, sort_keys=True) + "\n"


def write() -> list[Path]:
    md, js = render()
    paths = [PACKAGE / "CATALOGUE.md", PACKAGE / "catalogue.json"]
    for path, text in zip(paths, (md, js)):
        path.write_text(text)
    return paths
