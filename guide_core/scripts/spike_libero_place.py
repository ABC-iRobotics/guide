# --------------------------------------------------------------------------- BDDL
def sexpr(text):
    tokens = re.findall(r"\(|\)|[^\s()]+", re.sub(r";[^\n]*", "", text))
    stack = [[]]
    for tok in tokens:
        if tok == "(":
            stack.append([])
        elif tok == ")":
            done = stack.pop()
            stack[-1].append(done)
        else:
            stack[-1].append(tok)
    return stack[0][0]


def section(tree, key):
    return next((s[1:] for s in tree if isinstance(s, list) and s and s[0] == key), [])


def typed(items):
    """`a b - cat c - cat2` -> {a: cat, b: cat, c: cat2}"""
    out, pending = {}, []
    it = iter(items)
    for tok in it:
        if tok == "-":
            cat = next(it)
            out.update({p: cat for p in pending})
            pending = []
        else:
            pending.append(tok)
    return out


def parse_bddl(text):
    tree = sexpr(text)
    regions = {}
    for reg in section(tree, ":regions"):
        name, body = reg[0], {k[0]: k[1:] for k in reg[1:]}
        target = body[":target"][0]
        ranges = [[float(x) for x in r] for r in body.get(":ranges", [[]])[0]] if ":ranges" in body else []
        yaw = [float(x) for x in body[":yaw_rotation"][0][0]] if ":yaw_rotation" in body else None
        regions[f"{target}_{name}"] = {"target": target, "ranges": ranges, "yaw": yaw}
    return {"regions": regions,
            "fixtures": typed(section(tree, ":fixtures")),
            "objects": typed(section(tree, ":objects")),
            "init": [[t.lower() for t in fact] for fact in section(tree, ":init")]}


def supported(fact, bddl):
    """`on <instance> main_table_<region>`: the only init fact this front-end lays out."""
    return (len(fact) == 3 and fact[0] == "on"
            and bddl["regions"].get(fact[2], {}).get("target") == "main_table")


def shape(fact, bddl):
    """`on akita_black_bowl_1 cookies_1` -> `on <object> <object>`."""
    def kind(a):
        if a in bddl["objects"]:
            return "<object>"
        if a in bddl["fixtures"]:
            return "<fixture>"
        if a in bddl["regions"]:
            return "<table region>" if bddl["regions"][a]["target"] == "main_table" else "<fixture region>"
        return a
    return " ".join([fact[0], *map(kind, fact[1:])])


def unsupported_all_spatial():
    files = sorted(SPATIAL.glob("*.bddl"))
    shapes, facts, full = Counter(), 0, 0
    for f in files:
        b = parse_bddl(f.read_text())
        bad = [shape(x, b) for x in b["init"] if not supported(x, b)]
        shapes.update(bad)
        facts += len(b["init"])
        full += not bad
    return {"files": len(files), "init_facts": facts, "supported": facts - sum(shapes.values()),
            "files_fully_supported": full, "unsupported_by_shape": dict(shapes.most_common())}


# --------------------------------------------------------------------------- YAML
def to_replicator_yaml(bddl, rest_z, body_prims, offsets=None):
    """Replicator YAML (as a dict) placing every `on <instance> main_table_<region>` fact.
    rest_z: {instance: rest height above the table}; body_prims: {instance: scene-relative
    path of the prim to write}; offsets (debug attempt `offset` only): {instance: (dx, dy)} of
    the body that should land in the region, relative to the written prim, at yaw 0."""
    facts = [f for f in bddl["init"] if supported(f, bddl)]
    groups = {}
    for k in range(0, len(facts), PER_TRIGGER):
        reg = {}
        for _, inst, region in facts[k:k + PER_TRIGGER]:
            r = bddl["regions"][region]
            (x0, y0, x1, y1), = r["ranges"]  # ponytail: one rectangle per region (all of Spatial); a union needs one node per rectangle
            dx, dy = (offsets or {}).get(inst, (0.0, 0.0))
            x0, x1, y0, y1 = (round(v, 4) for v in (x0 - dx, x1 - dx, y0 - dy, y1 - dy))
            z = round(rest_z[inst] + 0.001, 4)
            rot = ({"distribution.uniform": {"lower": [0.0, 0.0, round(math.degrees(r["yaw"][0]), 4)],
                                             "upper": [0.0, 0.0, round(math.degrees(r["yaw"][1]), 4)],
                                             "name": f"{inst}_rotation"}}
                   if r["yaw"] else [0.0, 0.0, 0.0])
            reg[inst] = {"get.prims": {"path_pattern": re.escape(body_prims[inst]) + "$"}}
            reg[f"with.{inst}"] = {"modify.pose": {
                "position": {"distribution.uniform": {"lower": [x0, y0, z], "upper": [x1, y1, z],
                                                      "name": f"{inst}_position"}},
                "rotation": rot,
                "write_to_usd": True}}
        groups[f"place_{k // PER_TRIGGER}"] = reg
    doc = {g: {"randomizer.register": {g: reg}} for g, reg in groups.items()}
    doc.update({f"on_{g}": {"trigger.on_custom_event": {"event_name": EVENT}} for g in groups})
    doc.update({f"with_{g}": {f"with.on_{g}": {f"randomizer.{g}": None}} for g in groups})
    return doc


def selftest():
    b = parse_bddl(BDDL.read_text())
    r = b["regions"]
    assert r["main_table_plate_region"]["ranges"] == [[0.05, 0.19, 0.07, 0.21]]
    assert r["main_table_cabinet_region"]["yaw"] == [2.6613777765410678, 2.7242096296128633]
    assert b["objects"]["akita_black_bowl_2"] == "akita_black_bowl"
    assert ["on", "plate_1", "main_table_plate_region"] in b["init"]
    assert r["wooden_cabinet_1_top_region"]["ranges"] == []
    assert [f for f in b["init"] if not supported(f, b)] == []
    insts = [f[1] for f in b["init"]]
    doc = to_replicator_yaml(b, dict.fromkeys(insts, 0.0), {i: f"/objects/{i}" for i in insts})
    regs = {g: body["randomizer.register"][g] for g, body in doc.items() if "randomizer.register" in body}
    withs = [sum(k.startswith("with.") for k in reg) for reg in regs.values()]
    assert withs == [6, 1], withs
    assert sum("trigger.on_custom_event" in body for body in doc.values()) == len(regs)
    cab = next(reg for reg in regs.values() if "wooden_cabinet_1" in reg)
    assert cab["wooden_cabinet_1"]["get.prims"]["path_pattern"] == "/objects/wooden_cabinet_1$"
    pose = cab["with.wooden_cabinet_1"]["modify.pose"]
    assert pose["position"]["distribution.uniform"]["lower"] == [0.02, -0.28, 0.001]
    assert [pose["rotation"]["distribution.uniform"][k][2] for k in ("lower", "upper")] == [152.4857, 156.0857]
    assert regs["place_0"]["with.plate_1"]["modify.pose"]["rotation"] == [0.0, 0.0, 0.0]
    assert yaml.safe_load(yaml.safe_dump(doc, sort_keys=False)) == doc
    print("selftest ok:", withs, "with blocks per randomizer;", unsupported_all_spatial())


# --------------------------------------------------------------------------- Isaac
def task2():
    """Task 2's module (build_scene, step, check_joints); its SimulationApp starts in main() only."""
    spec = importlib.util.spec_from_file_location("spike_libero_isaac", HERE.parent / "spike_libero_isaac.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def yaw_deg(q):
    w, x, y, z = q
    return math.degrees(math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z)))


def r4(v):
    return np.round(np.asarray(v, dtype=float), 4).tolist()


def dist(a, b):
    return round(float(np.linalg.norm(np.asarray(a, float) - np.asarray(b, float))), 4)


def render(world, stage, path, frames=60, res=(1280, 720)):
    """One RGB frame from CAM; returns np.ptp (0 = uniform image, not saved)."""
    import omni.replicator.core as rep
    from PIL import Image

    rp = rep.create.render_product(CAM, res)
    ann = rep.AnnotatorRegistry.get_annotator("rgb")
    ann.attach([rp])
    for _ in range(frames):  # warm-up: shaders, textures (also 1 s of physics)
        world.step(render=True)
    img = np.asarray(ann.get_data())
    ann.detach()
    rp.destroy()
    ptp = int(np.ptp(img[..., :3])) if img.ndim == 3 and img.size else 0
    if ptp > 0:
        Image.fromarray(img[..., :3].astype(np.uint8)).save(path)
    return ptp


def finite(o):
    """NaN/inf -> None so the JSON stays standard: null = PhysX returned a non-finite value."""
    if isinstance(o, float):
        return o if math.isfinite(o) else None
    if isinstance(o, dict):
        return {k: finite(v) for k, v in o.items()}
    if isinstance(o, list):
        return [finite(v) for v in o]
    return o


def main(attempt=None):
    from isaacsim import SimulationApp

    app = SimulationApp({"headless": True})
    import importlib.metadata

    import omni.usd
    from guide_core.types.randomization import replicator_guide
    from isaacsim.core.api import World
    from isaacsim.core.prims import RigidPrim
    from pxr import Gf, Usd, UsdGeom

    yaml_out, out_path, tag = ((YAML_OUT, OUT, "place") if attempt is None else
                               (SPIKE / f"spike_libero_randomize_{attempt}.yaml",
                                SPIKE / f"spike_libero_place_{attempt}.json", f"place_{attempt}"))
    isaac = task2()
    prev = json.loads((DESIGN / "spike_libero_isaac.json").read_text())
    bddl = parse_bddl(BDDL.read_text())
    category = {**bddl["objects"], **bddl["fixtures"]}
    insts = [f[1] for f in bddl["init"] if supported(f, bddl) and f[1] in prev]
    fixtures = [i for i in insts if i in bddl["fixtures"]]
    region = {f[1]: bddl["regions"][f[2]] for f in bddl["init"] if f[1] in insts}
    out = {"_isaac": importlib.metadata.version("isaacsim"), "attempt": attempt and {attempt: ATTEMPTS[attempt]},
           "bddl": str(BDDL), "yaml": str(yaml_out),
           "frame": "PhysX world = /Scene_0 = table frame (table centred at the origin, top at z = 0)",
           "unsupported": [f for f in bddl["init"] if not supported(f, bddl)],
           "unsupported_all_spatial": unsupported_all_spatial(),
           "seeds": {}, "renders": {}}
    # _findings: interpretation recorded after the runs, not measured here: keep it across re-runs
    old = json.loads(out_path.read_text()) if out_path.exists() else {}
    out.update({k: old[k] for k in ("_findings",) if k in old})
    RENDERS.mkdir(parents=True, exist_ok=True)
    stage = omni.usd.get_context().get_stage()
    try:
        assets = {}
        for i in insts:
            assets.setdefault(category[i], []).append(i)
        isaac.build_scene(stage, assets)
        offsets = None
        if attempt == "offset":  # Geometry/Body/object (the colliders) relative to the written Body
            offsets = {i: tuple(UsdGeom.Xformable(stage.GetPrimAtPath(prev[i]["body_prim"] + "/object"))
                                .GetLocalTransformation().ExtractTranslation())[:2] for i in insts if i not in fixtures}
        doc = to_replicator_yaml(bddl, {i: prev[i]["rest_z_above_table"] for i in insts},
                                 {i: prev[i]["place_prim"].removeprefix(SCENE) for i in insts}, offsets)
        yaml_out.write_text(HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=None))
        out["randomizers"] = sum("randomizer.register" in g for g in doc.values())
        out["triggers"] = sum("trigger.on_custom_event" in g for g in doc.values())

        def rest_layout():
            """Task 2's measured rest layout (none of it inside a LIBERO region), so a pose that
            does not follow the write shows up as an error, not as a lucky in_region."""
            for i in insts:
                p = stage.GetPrimAtPath(prev[i]["place_prim"])
                p.GetAttribute("xformOp:translate").Set(Gf.Vec3d(*prev[i]["rest_pose"][:3]))
                if p.GetAttribute("xformOp:rotateXYZ"):
                    p.GetAttribute("xformOp:rotateXYZ").Set(Gf.Vec3f(0, 0, 0))

        rest_layout()
        out["xform_op_order_before"] = {i: [str(o) for o in UsdGeom.Xformable(stage.GetPrimAtPath(prev[i]["place_prim"])).GetXformOpOrderAttr().Get()] for i in insts}
        cam = UsdGeom.Camera.Define(stage, CAM)
        cam.CreateFocalLengthAttr(18.0)
        cam.CreateClippingRangeAttr(Gf.Vec2f(0.01, 100.0))  # USD's default near plane is 1 m here
        cam.AddTransformOp().Set(Gf.Matrix4d().SetLookAt(Gf.Vec3d(*EYE), Gf.Vec3d(*TARGET), Gf.Vec3d(0, 0, 1)).GetInverse())

        world = World(stage_units_in_meters=1.0, physics_dt=isaac.DT, rendering_dt=isaac.DT)
        t = time.perf_counter()
        state = replicator_guide.build(yaml_out, SCENE)
        out["build_s"] = round(time.perf_counter() - t, 2)
        if attempt == "tensor":
            replicator_guide.fire(state)
            rest_layout()
        world.reset()
        isaac.step(world, 1.0)

        # placed body (PhysX; for a fixture its Geometry/Body, welded to the written root) and
        # the second rigid body welded to it (Geometry/Body/object, the one with the colliders).
        # No contact-sensor prep: it authors PhysxRigidBodyAPI during play (in a first run that
        # re-parsed both fixtures; ~/libero_assets/spike/spike_libero_place_run1.log).
        pair = {i: (prev[i]["body_prim"], prev[i]["body_prim"] + "/object") for i in insts}
        views = {}

        def make_views():
            views.update({p: RigidPrim(p, reset_xform_properties=False, prepare_contact_sensors=False)
                          for ps in pair.values() for p in ps})

        def read():
            return {p: [np.asarray(a, float)[0] for a in v.get_world_poses()] for p, v in views.items()}

        def usd_xyz(i):
            m = UsdGeom.Xformable(stage.GetPrimAtPath(prev[i]["place_prim"])).ComputeLocalToWorldTransform(Usd.TimeCode.Default())
            return r4(m.ExtractTranslation())

        make_views()
        rest = read()
        out["settled"] = {i: {"body_xyz": r4(rest[b][0]), "object_xyz": r4(rest[o][0])} for i, (b, o) in pair.items()}
        fire_ms = []
        for seed in range(10):
            before = read()
            if attempt == "preplay":
                world.stop()
            t = time.perf_counter()
            samples = replicator_guide.fire(state, seed=seed)
            fire_ms.append(round((time.perf_counter() - t) * 1000, 1))
            if attempt == "preplay":
                world.reset()
                make_views()
            if attempt == "tensor":
                from isaacsim.core.prims import Articulation

                for i in fixtures:
                    yaw = math.radians(samples.get(f"{i}_rotation", [[0, 0, 0]])[0][2])
                    Articulation(prev[i]["body_prim"], reset_xform_properties=False).set_world_poses(
                        np.array([samples[f"{i}_position"][0]]), np.array([[math.cos(yaw / 2), 0, 0, math.sin(yaw / 2)]]))
            if seed == 0:
                out["xform_op_order_after_fire"] = {i: [str(o) for o in UsdGeom.Xformable(stage.GetPrimAtPath(prev[i]["place_prim"])).GetXformOpOrderAttr().Get()] for i in insts}
            after, usd = read(), {i: usd_xyz(i) for i in insts}
            isaac.step(world, 1.0)
            later = read()
            recs = out["seeds"][str(seed)] = {}
            for i, (b, o) in pair.items():
                (x0, y0, x1, y1), = region[i]["ranges"]
                lo, hi = np.degrees(region[i]["yaw"]) if region[i]["yaw"] else (0.0, 0.0)
                p, yaw = after[b][0], yaw_deg(after[b][1])
                s = samples[f"{i}_position"][0]
                c = after[o][0] if attempt == "offset" else p  # what the region is checked on
                off = [dist(rest[b][0], rest[o][0]), dist(after[b][0], after[o][0]), dist(later[b][0], later[o][0])]
                recs[i] = {
                    "sample_xyz": r4(s), "sample_yaw_deg": round(samples.get(f"{i}_rotation", [[0, 0, 0]])[0][2], 3),
                    "usd_place_prim_xyz": usd[i],
                    "physx_xyz": r4(p), "physx_yaw_deg": round(yaw, 3),
                    "in_region": bool(x0 - TOL_M <= c[0] <= x1 + TOL_M and y0 - TOL_M <= c[1] <= y1 + TOL_M),
                    "err_to_sample_m": dist(p[:2], s[:2]),
                    "drift_m": dist(later[b][0], p),
                    "yaw_ok": bool(abs((yaw - (lo + hi) / 2 + 180) % 360 - 180) <= (hi - lo) / 2 + TOL_DEG),
                    "two_body_follow": {
                        "body_moved_m": dist(after[b][0], before[b][0]),
                        "object_moved_m": dist(after[o][0], before[o][0]),
                        "object_xyz": r4(after[o][0]),
                        "offset_rest_m": off[0], "offset_after_fire_m": off[1], "offset_after_1s_m": off[2],
                        "followed": abs(off[1] - off[0]) < TOL_M},
                }
            if seed < 3:
                path = RENDERS / f"{tag}_seed{seed}.png"
                out["renders"][path.name] = ptp = render(world, stage, str(path))
                if ptp == 0:
                    out["renders"][path.name] = "uniform image, not saved"
        out["fire_ms"] = round(float(np.mean(fire_ms)), 1)
        out["fire_ms_all"] = fire_ms
        recs = out["seeds"].values()
        out["summary"] = {i: {"in_region": sum(r[i]["in_region"] for r in recs),
                              "drift_lt_1cm": sum(r[i]["drift_m"] < DRIFT_M for r in recs),
                              "yaw_ok": sum(r[i]["yaw_ok"] for r in recs),
                              "two_body_followed": sum(r[i]["two_body_follow"]["followed"] for r in recs),
                              "of": len(recs)} for i in insts}

        # the drawers after ten Replicator pose writes to the cabinet's root, as in Task 2
        cab = "wooden_cabinet_1"
        _, joints = isaac.check_joints(world, stage, prev[cab]["body_prim"], isaac.OPEN_AT[category[cab]])
        out["drawer_recheck"] = {
            "body_xyz": r4(read()[pair[cab][0]][0]),
            "joints": joints,
            "opens_and_closes": all(abs(j["reached_open"] - j[j["open_at"]]) < 0.005
                                    and abs(j["reached_closed"] - j["upper" if j["open_at"] == "lower" else "lower"]) < 0.005
                                    for j in joints.values()),
            "task2": prev["_articulation"][cab]["joints"]}
    except Exception as e:  # noqa: BLE001
        out["_error"] = f"{type(e).__name__}: {e}"
        raise
    finally:
        out_path.write_text(json.dumps(finite(out), indent=1) + "\n")
        print(json.dumps(finite({k: v for k, v in out.items() if k != "seeds"}), indent=1), flush=True)
        app.close()


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        selftest()
    else:  # --attempt=<name>: a debugging variant, written next to the renders, not to docs/design
        main(next((a.removeprefix("--attempt=") for a in sys.argv if a.startswith("--attempt=")), None))
